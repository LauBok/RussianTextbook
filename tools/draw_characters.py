def _curls(n=9, r=11.2, a0=196, a1=-16, bump=2.5):
    """迪马的卷发外缘：沿头顶一串向外凸的小弧。"""
    pts = [(r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), -r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]
