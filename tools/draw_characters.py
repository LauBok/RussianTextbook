NARG = {"M": 2, "L": 2, "T": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "A": 7, "Z": 0}


def fmt(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def tpath(d, s, ox, oy):
    toks = re.findall(r"[A-Za-z]|-?\d*\.?\d+", d)
    out, cmd, i = [], None, 0
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            out.append(t)
            i += 1
            if cmd == "Z":
                continue
        n = NARG[cmd]
        vals = [float(x) for x in toks[i:i + n]]
        i += n
        if cmd == "H":
            vals = [vals[0] * s + ox]
        elif cmd == "V":
            vals = [vals[0] * s + oy]
        elif cmd == "A":
            vals = [vals[0] * s, vals[1] * s, vals[2], vals[3], vals[4], vals[5] * s + ox, vals[6] * s + oy]
            out.append(" ".join(fmt(v) if k not in (3, 4) else str(int(v)) for k, v in enumerate(vals)))
            continue
        else:
            vals = [v * s + (ox if k % 2 == 0 else oy) for k, v in enumerate(vals)]
        out.append(" ".join(fmt(v) for v in vals))
    return re.sub(r"([A-Z]) ", r"\1", " ".join(out))


def attrs(a):
    return "".join(f' {k.replace("_", "-")}="{v}"' for k, v in a.items())


def render(els, s=1.0, ox=0.0, oy=0.0):
    """els: ("p", d, {attrs}) / ("c", cx, cy, r, {attrs}) / ("e", cx, cy, rx, ry, {attrs}) / ("dot", cx, cy, r)"""
    out = []
    for e in els:
        k = e[0]
        if k == "p":
            out.append(f'<path d="{tpath(e[1], s, ox, oy)}"{attrs(e[2] if len(e) > 2 else {})}/>')
        elif k == "c":
            out.append(f'<circle cx="{fmt(e[1]*s+ox)}" cy="{fmt(e[2]*s+oy)}" r="{fmt(e[3]*s)}"{attrs(e[4] if len(e) > 4 else {})}/>')
        elif k == "e":
            out.append(f'<ellipse cx="{fmt(e[1]*s+ox)}" cy="{fmt(e[2]*s+oy)}" rx="{fmt(e[3]*s)}" ry="{fmt(e[4]*s)}"{attrs(e[5] if len(e) > 5 else {})}/>')
        elif k == "dot":
            r = max(e[3] * s, 0.55)
            out.append(f'<circle cx="{fmt(e[1]*s+ox)}" cy="{fmt(e[2]*s+oy)}" r="{fmt(r)}" fill="#2b2b2b" stroke="none"/>')
    return "".join(out)


